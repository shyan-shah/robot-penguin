"""Generate firmware/penguin/include/motions.h from the simulated motion library.

Single source of truth: every keyframe the robot plays is the same keyframe that
was run through the physics sim and checked for self-collision against the CAD.
Re-run this whenever behaviours.py or the tuned parameters change.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "sim"))

import behaviours as B                                           # noqa: E402

OUT = os.path.join(HERE, "penguin", "include", "motions.h")
JOINTS = ["hip_R", "hip_L", "ankle_R", "ankle_L", "flipper_R", "flipper_L", "beak"]
TUNED = os.path.join(ROOT, "sim", "tuned")


def load(name, default=None):
    try:
        return json.load(open(os.path.join(TUNED, name)))
    except Exception:
        return default


def frames(motion, hz=50):
    """Flatten a Motion into evenly spaced frames the MCU can just index."""
    n = max(2, int(round(motion.duration * hz)) + 1)
    out = []
    for i in range(n):
        t = motion.duration * i / (n - 1)
        p = motion.sample(t)
        out.append([round(p[j], 1) for j in JOINTS])
    return out


def main():
    gait = load("gait.json", {})
    gparams = gait.get("params", {})
    learned = load("getup_learned.json", {})

    lib = {}
    for name, m in B.EMOTES.items():
        lib["EM_" + name] = (m, "emote")
    for name, m in B.TRICKS.items():
        lib["TR_" + name] = (m, "trick")
    for name, fn in B.DANCES.items():
        lib["DA_" + name] = (fn(), "dance")
    if gparams:
        g = {k: gparams[k] for k in ("roll", "yaw", "phase", "period", "toe_out")}
        lib["GAIT_walk"] = (B.waddle(**g), "gait")
        lib["GAIT_turn_L"] = (B.turn(direction=1), "gait")
        lib["GAIT_turn_R"] = (B.turn(direction=-1), "gait")

    rows, index = [], []
    for key, (m, kind) in sorted(lib.items()):
        f = frames(m)
        # int16_t, not int8_t: flipper travel runs -95..185 deg
        rows.append("static const int16_t %s[][7] = {\n%s\n};" % (
            key, "\n".join("  {%s}," % ", ".join("%4d" % round(v) for v in fr) for fr in f)))
        index.append((key, kind, len(f), m.duration, getattr(m, "loop", False)))

    hdr = ["// GENERATED by firmware/export_motions.py - do not edit by hand.",
           "// Source: sim/behaviours.py + sim/tuned/*.json",
           "#pragma once", "#include <stdint.h>", "",
           "// joint order: hip_R, hip_L, ankle_R, ankle_L, flipper_R, flipper_L, beak",
           "#define MOTION_HZ 50", "#define N_JOINTS 7", ""]
    hdr += rows
    hdr += ["", "struct MotionDef { const char* name; const int16_t (*frames)[7];"
                " uint16_t n; uint8_t loop; };", "",
            "static const MotionDef MOTIONS[] = {"]
    for key, kind, n, dur, loop in index:
        hdr.append('  {"%s", %s, %d, %d},' % (key, key, n, 1 if loop else 0))
    hdr += ["};", "static const uint8_t N_MOTIONS = %d;" % len(index), ""]

    # Name tables in the SAME sorted order the host uses when it packs
    # learned.bin, so an emote index means the same thing on both sides.
    # Hand-written copies of these drift; generated ones cannot.
    sys.path.insert(0, os.path.join(ROOT, "brain"))
    import actions
    hdr += ["// index order must match brain/actions.py - do not reorder",
            "static const char* const EMOTE_NAMES[] = {%s};"
            % ", ".join('"%s"' % k for k in sorted(actions.EMOTES)),
            "static const uint8_t N_EMOTES = %d;" % len(actions.EMOTES),
            "static const char* const TRICK_NAMES[] = {%s};"
            % ", ".join('"%s"' % k for k in sorted(actions.TRICKS)),
            "static const uint8_t N_TRICKS = %d;" % len(actions.TRICKS), ""]

    # tuned constants the firmware needs at runtime
    hdr += ["// --- tuned in simulation (sim/tuned/gait.json) ---",
            "#define BAL_KP %.4ff" % gparams.get("kp", 0.6),
            "#define BAL_KD %.4ff" % gparams.get("kd", 0.05),
            "#define BAL_CLIP_DEG 14.0f",
            "#define LEAN_SCALE %.3ff" % gparams.get("lean_scale", 1.0), ""]
    if learned:
        hdr.append("// --- learned fall recovery (sim/tuned/getup_learned.json) ---")
        for kind, d in learned.items():
            p = d["params"]
            hdr.append("// %-5s recovers=%s  final_up=%.3f" % (kind, d["recovered"], d["final_up"]))
            hdr.append("#define GETUP_%s_FREQ %.3ff" % (kind.upper(), p["freq"]))
            hdr.append("#define GETUP_%s_AMPR %.1ff" % (kind.upper(), p["amp_R"]))
            hdr.append("#define GETUP_%s_AMPL %.1ff" % (kind.upper(), p["amp_L"]))
            hdr.append("#define GETUP_%s_CENTRE %.1ff" % (kind.upper(), p["centre"]))
            hdr.append("#define GETUP_%s_PHASE %.3ff" % (kind.upper(), p["phase"]))
            hdr.append("#define GETUP_%s_HIP %.1ff" % (kind.upper(), p["hip"]))
            hdr.append("#define GETUP_%s_ANK %.1ff" % (kind.upper(), p["ank"]))
            hdr.append("#define GETUP_%s_ANKPH %.3ff" % (kind.upper(), p["ank_phase"]))
            hdr.append("#define GETUP_%s_RAMP %.2ff" % (kind.upper(), p["ramp"]))
            hdr.append("#define GETUP_%s_WORKS %d" % (kind.upper(), 1 if d["recovered"] else 0))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(hdr) + "\n")
    total = sum(n for _, _, n, _, _ in index)
    print("wrote %s" % OUT)
    print("  %d motions, %d frames, %d bytes of table" % (len(index), total, total * 7))
    for key, kind, n, dur, loop in index:
        print("    %-14s %-6s %3d frames  %5.2f s%s" % (key, kind, n, dur, "  (loops)" if loop else ""))


if __name__ == "__main__":
    main()
